def render(name):
    """The bytes for one fixture. ONE code path, so `--install` and `--out` cannot disagree."""
    value = BUILDERS[name]()
    if name.endswith(".rss"):
        return value.encode("utf-8")
    if name.endswith(".jsonl"):
        return ("\n".join(json.dumps(row, ensure_ascii=False) for row in value) + "\n").encode("utf-8")
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def _write(path, blob):
    d = os.path.dirname(path)
    if d:
        os.makedirs(d, exist_ok=True)
    with open(path, "wb") as f:
        f.write(blob)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate this repo's synthetic test fixtures.")
    ap.add_argument("--out", help="write every fixture into this directory, named by basename")
    ap.add_argument("--install", action="store_true",
                    help="write every fixture to its tracked location in this repo")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if a tracked fixture differs from what this generator emits")
    a = ap.parse_args(argv)
    if not (a.out or a.install or a.check):
        ap.error("pick one of --out / --install / --check")

    if a.out:
        for name in BUILDERS:
            _write(os.path.join(a.out, name), render(name))

    if a.install:
        for name, rel in TARGETS.items():
            _write(os.path.join(REPO, rel), render(name))
            print("wrote %s" % rel)

    if a.check:
        bad = 0
        for name, rel in TARGETS.items():
            p = os.path.join(REPO, rel)
            if not os.path.isfile(p):
                print("MISSING   %s" % rel, file=sys.stderr)
                bad += 1
                continue
            live = open(p, "rb").read().replace(b"\r\n", b"\n")
            if live != render(name).replace(b"\r\n", b"\n"):
                print("DRIFTED   %s  (run: python tools/make_fixtures.py --install)" % rel,
                      file=sys.stderr)
                bad += 1
        if bad:
            print("%d fixture(s) do not match the generator. A real record cannot be "
                  "regenerated, so this is either an edit that belongs in the generator or a "
                  "pasted record." % bad, file=sys.stderr)
            return 1
        print("make_fixtures: %d fixture(s) match the generator" % len(TARGETS))
    return 0


if __name__ == "__main__":
    sys.exit(main())
